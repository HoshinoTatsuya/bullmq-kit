import { deepFreeze } from '../../deep-freeze';

/**
 * Ответы скрипта «проверить и удалить» по одному хэшу. Различимы все причины
 * «не удалили»: «жива», «молода» и «не смогли проверить» лечатся по-разному.
 */
export const ORPHAN_VERDICT = {
  /** Задача в одном из индексов (или её id ждёт отложенная задача дедупликации `dn:`). */
  alive: 0,
  /** Удалён хэш и его хвосты. */
  deleted: 1,
  /** dryRun: удалили бы. */
  wouldDelete: 2,
  /** Ключа нет или он не хэш: удалять нечего. */
  notHash: 3,
  /** Моложе грейса по полю `timestamp`. */
  young: 4,
  /** `timestamp` есть, но не число — возраст неизвестен, удалять нельзя. */
  unknownAge: 5,
  /** Индекс неожиданного типа — членство не проверить, удалять нельзя. */
  unverifiable: 6,
  /**
   * Хэш без `timestamp`, увиденный сиротой впервые: удаляется только на
   * повторном наблюдении не раньше грейса (см. `checkAndDelete`).
   */
  untimestamped: 7,
  /**
   * Хэш с `timestamp`, но без полей, которые BullMQ пишет вместе с ним
   * (`BULLMQ_KEYS.JOB_SHAPE_FIELDS`): не хэш задачи, удалять нельзя.
   */
  notJob: 8,
  /**
   * Ключ лежит в пространстве другой очереди BullMQ, вложенной префиксом
   * (`<prefix>:x:<id>` очереди `x` с префиксом `<prefix>`): удалять нельзя.
   */
  nested: 9,
  /**
   * Хэш вне индексов, но у задачи живой `:lock`: её держит воркер (переход
   * между индексами ещё не записан или рассинхрон). Удалять нельзя — воркер
   * доработает и не найдёт тела задачи.
   */
  locked: 10,
} as const;

/** Почему прогон остановился раньше конца обхода. */
export const CLEANUP_STOP_REASON = {
  /** Потолок проверенных хэшей (`maxJobsPerRun`). */
  jobs: 'jobs',
  /** Потолок ключей SCAN (`maxScannedKeysPerRun`). */
  keys: 'keys',
  /** Потолок длительности (`maxRunMs`). */
  time: 'time',
} as const;

deepFreeze(CLEANUP_STOP_REASON);

deepFreeze(ORPHAN_VERDICT);
