import { deepFreeze } from '../../deep-freeze';

/**
 * Версии BullMQ, раскладку ключей которых уборка знает, — диапазон на каждый
 * проверенный мажор. Очередь другой версии не убирается: уборка удаляет ключи,
 * и незнакомая раскладка (новый служебный ключ, другой индекс статуса)
 * превратила бы «не смогли проверить» в «удалили».
 *
 * Все границы — проверенные, а не заявленные: весь набор уборки идёт против
 * каждой (`pnpm test`: `test:oldest` — 5.72.0, `test:bullmq5` — последняя 5,
 * `test:bullmq6-oldest` — 6.0.0, `test:latest` — последняя 6; псевдонимы в
 * devDependencies). Младше 5.72.0 нет `keepLastIfActive` (ключ `dn:`), и на
 * 5.71.1 набор красный.
 *
 * BullMQ 6 сверена с 5 по исходникам (Lua установленных 5.81 и 6.0/6.7) и
 * прогоном набора: имена и типы ключей очереди те же (`QueueKeys` совпадает),
 * хэш задачи и `dn:`/`de:` пишутся теми же полями. Отличия, которые уборка
 * учитывает: пауза больше не переносит `wait` в `paused` (задачи остаются в
 * `wait`, а список `paused` — наследство очередей, поставленных на паузу
 * BullMQ 5; он по-прежнему проверяется), ключи relay лежат в
 * `<prefix>::relay:…` — вне пространства очередей `<prefix>:<имя>:…`.
 *
 * Верхняя граница мажора — последний проверенный МИНОР (патчи внутри него
 * принимаются): новые служебные ключи BullMQ вводит в минорах (`dn:` — 5.72,
 * `repeat:` job schedulers — 5.16, relay — 6.x), и «весь мажор» пропускал бы
 * их до проверки. Тест держит каждую границу равной версии псевдонима, против
 * которого идёт набор: подъём devDependency без прогона набора и подъёма
 * границы — красный.
 */
export const BULLMQ_SUPPORTED_VERSIONS = {
  /** Диапазон на мажор: `MIN` — проверенная нижняя `[мажор, минор, патч]`, `MAX_MINOR` — последний проверенный `[мажор, минор]`. */
  RANGES: [
    { MIN: [5, 72, 0], MAX_MINOR: [5, 81] },
    { MIN: [6, 0, 0], MAX_MINOR: [6, 7] },
  ],
  /** `<очередь>:meta`, поле `version` = `bullmq:X.Y.Z` — его пишет каждый `new Queue` (проба на 5.81.3 и 6.7.7). */
  META_SUFFIX: 'meta',
  META_FIELD: 'version',
  META_PREFIX: 'bullmq:',
} as const;

deepFreeze(BULLMQ_SUPPORTED_VERSIONS);
