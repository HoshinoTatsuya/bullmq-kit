/** Захват слота пула группой. */
export interface FairSlot {
  /** Потолок пула (целое > 0): общий на все группы. */
  readonly poolLimit: number;
  /** Срок слота, мс — время возврата после смерти держателя, как у `GroupConcurrency`. */
  readonly ttlMs: number;
  /** Вес группы (число > 0, по умолчанию 1): доля — `потолок · вес / Σ весов активных`. */
  readonly weight?: number;
  /**
   * Сколько группа считается ждущей после отказа, мс (по умолчанию 60 000).
   * Не меньше интервала повтора её задач (`maxDelayMs` у `acquireOrDelay`):
   * иначе между повторами она «пропадает», и крупная группа занимает пул целиком.
   */
  readonly waitTtlMs?: number;
}
