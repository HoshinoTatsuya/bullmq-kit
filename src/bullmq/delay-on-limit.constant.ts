import { deepFreeze } from '../deep-freeze';

/**
 * Значения по умолчанию `acquireOrDelay`. Подсказка `retryAfterMs` — ХУДШИЙ
 * случай: когда слот освободится, если ни один держатель его не снимет и не
 * продлит. Держатель, закончивший работу, снимает слот раньше, а с продлением
 * (`withSlot`) подсказка почти всегда равна полному сроку. Поэтому задержка
 * растёт экспоненциально от `MIN_DELAY_MS`, а подсказка — только потолок.
 */
export const DELAY_ON_LIMIT_DEFAULTS = {
  /** Нижняя граница: подсказка в 1 мс превратила бы отказ в цикл active→delayed→wait. */
  MIN_DELAY_MS: 100,
  /** Верхняя граница: ожидающая задача перепроверяет слот не реже. */
  MAX_DELAY_MS: 60_000,
  /** Задержка, когда подсказки нет: группа закрыта (`limit: 0`) и по сроку не освободится. */
  CLOSED_GROUP_DELAY_MS: 60_000,
  /**
   * Случайная добавка: задачи, отложенные до одного и того же истечения, иначе
   * проснулись бы в одну миллисекунду, и слот достался бы одной, а остальные
   * снова ушли бы в delayed — толпой на каждом освобождении.
   */
  JITTER_MS: 250,
  /** Доля задержки в разбросе добавки: `[0, max(JITTER_MS, задержка · доля))`. */
  JITTER_FRACTION: 0.25,
  /** Потолок показателя `2ⁿ`: дальше задержку держит `maxDelayMs`, а степень не уходит в Infinity. */
  MAX_BACKOFF_EXPONENT: 30,
} as const;

deepFreeze(DELAY_ON_LIMIT_DEFAULTS);
