import { deepFreeze } from '../deep-freeze';

/**
 * Исходы захвата слота группы — значениями, а не строками у вызывающего:
 * гейты хардкода проектов запрещают сравнение с литералом (`outcome ===
 * 'limit'`), и своя копия этих строк в каждом проекте — второй словарь той же
 * величины. Тип исхода выводится отсюда же.
 */
export const ACQUIRE_OUTCOME = {
  /** Занят новый слот. */
  acquired: 'acquired',
  /** Держатель уже держит слот (`acquire` продлил его, `reserve` — не тронул). */
  held: 'held',
  /** Потолок исчерпан — единственный отказ. */
  limit: 'limit',
} as const;

deepFreeze(ACQUIRE_OUTCOME);
