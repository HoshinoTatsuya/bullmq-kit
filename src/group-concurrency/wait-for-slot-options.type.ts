/** Ожидание слота (`acquireWaiting`, `withSlot(..., { waitMs })`). */
export interface WaitForSlotOptions {
  /** Сколько ждать слот, мс (0 — одна попытка). Не дождались — исход `limit`. */
  readonly timeoutMs: number;
  /** Отмена ожидания: исход `limit`, из очереди ожидающих — сразу. */
  readonly signal?: AbortSignal;
  /**
   * Страховочная перепроверка, мс (по умолчанию 1 000): слот, освобождённый по
   * сроку (держатель умер) или снятый `clear`, публикации не даёт, и ожидающий
   * узнаёт о нём перепроверкой. Регистрация в очереди живёт 3 таких интервала.
   */
  readonly pollMs?: number;
}
