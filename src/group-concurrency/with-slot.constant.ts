import { deepFreeze } from '../deep-freeze';

/** Ритм и запас удержания слота в `withSlot`. */
export const WITH_SLOT = {
  /** Доля срока слота между продлениями: три попытки продлить, пока слот жив. */
  HEARTBEAT_FRACTION: 3,
  /**
   * Запас до истечения срока, с которым работа прерывается: `ttlMs / 10`.
   * Срок в Redis отсчитан от ИСПОЛНЕНИЯ продления, а оно не раньше его
   * отправки, поэтому «отправка последнего подтверждённого + ttl» — самый
   * ранний момент, когда слот может достаться другому. Запас покрывает
   * опоздание таймера при занятом цикле событий.
   */
  LOSS_MARGIN_FRACTION: 10,
  /**
   * Потолок `ttlMs`: предел таймера Node (2^31 − 1 мс, ~24.8 сут). Больший срок
   * Node молча заменяет на 1 мс (TimeoutOverflowWarning) — продление шло бы
   * непрерывно, а дедлайн потери срабатывал бы сразу.
   */
  MAX_TTL_MS: 2_147_483_647,
  /** Страховочная перепроверка ожидающего слот, мс (`acquireWaiting`, `pollMs`). */
  WAIT_POLL_MS: 1_000,
  /**
   * Регистрация ожидающего живёт столько перепроверок: умерший ожидающий
   * снимается из очереди через три пропущенные, а не держит её вечно.
   */
  WAITER_TTL_POLLS: 3,
} as const;

deepFreeze(WITH_SLOT);
